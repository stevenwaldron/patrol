"""The list of sites to monitor, loaded and validated from a YAML file.

In Kubernetes the file is mounted from a ConfigMap generated by the Helm chart,
so adding a site is a Git commit, reviewed like any other change.
"""

import re
from dataclasses import dataclass

import yaml

_ID_PATTERN = re.compile(r"^[a-z0-9][a-z0-9-]{0,62}$")


@dataclass(frozen=True)
class Site:
    id: str
    name: str
    url: str
    timeout_seconds: float = 10.0


def parse_sites(raw: dict) -> list[Site]:
    entries = (raw or {}).get("sites")
    if not isinstance(entries, list) or not entries:
        raise ValueError("sites file must contain a non-empty 'sites' list")

    sites, seen = [], set()
    for i, entry in enumerate(entries):
        where = f"sites[{i}]"
        if not isinstance(entry, dict):
            raise ValueError(f"{where}: must be a mapping")
        site_id = str(entry.get("id", ""))
        url = str(entry.get("url", ""))
        if not _ID_PATTERN.match(site_id):
            raise ValueError(f"{where}: id {site_id!r} must be lowercase letters, digits and dashes")
        if site_id in seen:
            raise ValueError(f"{where}: duplicate id {site_id!r}")
        if not url.startswith(("http://", "https://")):
            raise ValueError(f"{where}: url {url!r} must start with http:// or https://")
        timeout = float(entry.get("timeout_seconds", 10))
        if not 1 <= timeout <= 30:
            raise ValueError(f"{where}: timeout_seconds must be between 1 and 30")
        seen.add(site_id)
        sites.append(Site(site_id, str(entry.get("name") or site_id), url, timeout))
    return sites


def load_sites(path: str) -> list[Site]:
    with open(path, encoding="utf-8") as f:
        return parse_sites(yaml.safe_load(f))
